export const BASE_TRANSLATIONS = { en, bn, hi } as const;

/** Translate with fallback to English and {placeholder} filling. */
export function translate(lang: string, key: I18nKey, vars?: Record<string, string | number>, overrides?: Record<string, string>): string {
  const table = (BASE_TRANSLATIONS as Record<string, Partial<Record<I18nKey, string>>>)[lang] ?? {};
  const raw = overrides?.[key] ?? table[key] ?? en[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : raw;
}
